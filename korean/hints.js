(function(){
const keys=Object.keys(window.HINTS);
const map={},noscan=new Set();
keys.forEach(k=>{const kk=k.replace(/!$/,'');map[kk]=window.HINTS[k];if(k.endsWith('!'))noscan.add(kk);});
const sorted=Object.keys(map).sort((a,b)=>b.length-a.length);
const isH=c=>/[가-힣]/.test(c);
function find(word){
  if(map[word])return word;
  for(const k of sorted){if(k.length>=2&&word.startsWith(k))return k;}
  return null;
}
function fmt(k,word){
  const v=map[k],t=v[0],s=v.slice(1);
  if(t==='h'){ // 逐字對照
    const syl=[...k].filter(isH),han=[...s];
    let out='';han.forEach((c,i)=>{out+=isH(c)?c:(c+(syl[i]&&syl[i]!==c?`(${syl[i]})`:''));});
    const rest=word&&word!==k&&word.startsWith(k)?'＋'+word.slice(k.length):'';
    return {t:'漢',c:'h',txt:out+(rest&&/^(하다|되다|하소서|시키다|적|히)$/.test(rest.slice(1))?rest:'')};
  }
  return {t:t==='e'?'外':t==='m'?'聯想':'漢',c:t==='e'?'e':t==='m'?'m':'h',txt:s};
}
// 給一個詞（可能含空格）找提示，回傳 [{t,c,txt}]
window.hintFor=function(word){
  const w=String(word).replace(/[?.!,]/g,'').trim();if(!w)return [];
  if(map[w])return [fmt(w,w)];
  const out=[];
  w.split(/\s+/).forEach(tok=>{const k=find(tok);if(k&&!out.some(o=>o.k===k)){const f=fmt(k,tok);f.k=k;out.push(f);}});
  return out.slice(0,3);
};
// 掃描例句：找出其中的漢字詞與外來語（2 音節以上）
window.hintScan=function(sent){
  const out=[];
  String(sent).replace(/[?.!,「」]/g,' ').split(/\s+/).forEach(tok=>{
    if(!tok)return;
    for(const k of sorted){
      if(k.length<2||noscan.has(k)||k.includes(' '))continue;
      const t=map[k][0];if(t==='m')continue;
      if(tok.startsWith(k)){if(!out.some(o=>o.k===k))out.push({k,v:map[k]});break;}
    }
  });
  return out.slice(0,4).map(o=>{const v=o.v,t=v[0],s=v.slice(1);
    if(t==='h'){const syl=[...o.k];return o.k+'＝'+[...s].map((c,i)=>isH(c)?c:c).join('');}
    return o.k+'＝'+s.split(/[（：；→]/)[0];});
};
window.hintHTML=function(word){
  return hintFor(word).map(h=>`<span class="hint ${h.c}"><b>${h.t}</b>${esc(h.txt)}</span>`).join('');
};
window.scanHTML=function(sent){const a=hintScan(sent);return a.length?`<span class="hscan">💡 ${a.map(esc).join('・')}</span>`:'';};
})();
